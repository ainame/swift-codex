#!/usr/bin/env python3
"""Inventory upstream RPCs and experimental fields; source matches are not parity proof."""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "vendor/openai-codex"
PROTOCOL = UPSTREAM / "codex-rs/app-server-protocol"
SCHEMA = PROTOCOL / "schema/json"


def main() -> None:
    commit = subprocess.check_output(["git", "-C", str(UPSTREAM), "rev-parse", "HEAD"], text=True).strip()
    common = (PROTOCOL / "src/protocol/common.rs").read_text()
    api = (ROOT / "Sources/Codex/AppServerAPI.swift").read_text()
    transport = (ROOT / "Sources/Codex/AppServerTransport.swift").read_text()
    combined = json.loads((SCHEMA / "codex_app_server_protocol.v2.schemas.json").read_text())["definitions"]
    stable_params = {
        variant["properties"]["method"]["enum"][0]: combined.get(
            variant["properties"].get("params", {}).get("$ref", "").rsplit("/", 1)[-1], {}
        ).get("properties", {})
        for variant in combined["ClientRequest"]["oneOf"]
    }
    lines = ["# App-server surface inventory", "", f"Upstream: `{commit}`.", "",
             "Generated by `python3 Scripts/audit_app_server_surface.py`. Refresh during every sync,",
             "including unchanged upstream bases when auditing existing gaps. Entries marked",
             "`source match` are candidates for semantic review, not proof of working support.",
             "Trace options, serialization, dispatch, response, and tests before marking a feature",
             "implemented in UPSTREAM.md. Unmatched methods remain available only through raw RPC",
             "or the generic server handler; neither guarantees end-to-end behavior.", ""]
    for kind, source in (("ClientRequest", api), ("ServerRequest", transport)):
        schema = json.loads((SCHEMA / f"{kind}.json").read_text())
        entries = {}
        for variant in schema["oneOf"]:
            props = variant["properties"]
            method = props["method"]["enum"][0]
            param_ref = props.get("params", {}).get("$ref", "").rsplit("/", 1)[-1]
            params = schema.get("definitions", {}).get(param_ref, {})
            entries[method] = (param_ref, sorted(params.get("properties", {})))
        # Stable exports omit experimental methods. Rust wire declarations are
        # the complete method inventory for the pinned basis.
        macro = "client_request_definitions" if kind == "ClientRequest" else "server_request_definitions"
        body = common.split(macro + "! {", 1)[1].split("\n}", 1)[0]
        for method in re.findall(r'=>\s*"([^\"]+)"\s*\{', body):
            entries.setdefault(method, ("Rust-only export", []))
        lines += [f"## {kind} ({len(entries)} methods)", "",
                  "| Method | Parameter type | Stable exported fields | Swift source |",
                  "| --- | --- | --- | --- |"]
        for method, (param_ref, fields) in sorted(entries.items()):
            match = "source match" if f'"{method}"' in source else "unwrapped"
            lines.append(f"| `{method}` | `{param_ref}` | {', '.join(f'`{f}`' for f in fields) or '—'} | {match} |")
        lines.append("")
    lines += ["## Experimental request fields", "",
              "Stable JSON exports can omit these fields even when the Rust runtime supports them.",
              "Review every entry, including fields on already wrapped requests. Nested experimental",
              "types and handwritten SDK orchestration still require separate semantic review.", "",
              "| Experimental field | Stable combined schema | Swift wire key |", "| --- | --- | --- |"]
    fields = set()
    for path in sorted((PROTOCOL / "src").rglob("*.rs")):
        fields.update(re.findall(r'#\[experimental\("([^\"]+\.[^\"]+)"\)\]', path.read_text()))
    all_swift = "\n".join(path.read_text() for path in (ROOT / "Sources/Codex").glob("*.swift"))
    for field in sorted(fields):
        method, key = field.rsplit(".", 1)
        # This column deliberately only reports an occurrence, not which RPC sends it.
        exported = key in stable_params.get(method, {})
        match = "source match" if f'"{key}"' in all_swift else "unwrapped"
        lines.append(f"| `{field}` | {'present' if exported else 'omitted'} | {match} |")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
